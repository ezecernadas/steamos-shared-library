"""The systemd units that mount the shared library at boot, as text.

Why this matters: the library only works while the NTFS partition is mounted
with `ntfs3` and `windows_names`, and while `compatdata` and `shadercache` are
bind-mounted over it from ext4. These units make that happen at every boot.
They live in `/etc/systemd/system`, which survives SteamOS A/B updates
(docs/PLAN.md, "Architecture").

Three kinds of unit work together:

- a service that loads the `ntfs3` module, which some distros blacklist;
- the NTFS mount, which requires that service;
- one bind mount per Linux-only folder, bound to the NTFS mount.

This module only builds the file names and contents; the `unit_installer`
adapter writes them. To add a unit kind, write a `render_...` function and
include its result in `build_units`.
"""

from dataclasses import dataclass
from pathlib import PurePosixPath

from steamshare.core.library_layout import (
    LINUX_ONLY_DATA_DIRECTORY,
    LINUX_ONLY_DIRECTORIES,
    STEAMAPPS_DIRECTORY,
)
from steamshare.core.mounts import NTFS3_FILESYSTEM, build_ntfs3_mount_options

# Every generated file starts with this, so whoever opens it knows not to
# edit it by hand.
GENERATED_HEADER = (
    "# Generated by steamshare (`python -m steamshare install`).\n"
    "# Do not edit: running install again overwrites this file.\n"
)

NTFS3_LOADER_SERVICE = "steamshare-ntfs3.service"
NTFS3_KERNEL_MODULE = "ntfs3"

# Ubuntu (and so Zorin) and Arch (and so SteamOS) both merge /sbin and
# /usr/sbin into /usr, so this path reaches `modprobe` on both.
MODPROBE_PATH = PurePosixPath("/usr/sbin/modprobe")

# Stable across reboots and disk reordering, unlike /dev/sdX or /dev/nvmeXnYpZ.
DEVICE_BY_UUID_DIRECTORY = PurePosixPath("/dev/disk/by-uuid")

# The target that mounts local filesystems at boot.
LOCAL_FILESYSTEMS_TARGET = "local-fs.target"

# systemd reads `nofail` from Options= and then does not order the mount
# before local-fs.target, so a missing disk does not block boot. mount(8)
# accepts it too.
NOFAIL_OPTION = "nofail"

BIND_OPTION = "bind"
# A bind mount has no filesystem type of its own.
BIND_MOUNT_TYPE = "none"

MOUNT_UNIT_SUFFIX = ".mount"

# Characters systemd keeps as they are in an escaped unit name. Every other
# byte becomes `\xNN` (`man systemd.unit`, "String Escaping for Inclusion in
# Unit Names").
UNESCAPED_UNIT_NAME_CHARACTERS = frozenset(
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789:_."
)
UNIT_NAME_PATH_SEPARATOR = "-"


@dataclass(frozen=True)
class InstallConfig:
    """What the user tells `install` about their setup."""

    partition_uuid: str
    mount_point: PurePosixPath
    # The folder on the partition that contains `steamapps`.
    library_folder: str
    # The desktop user who runs Steam; owns the NTFS files and the ext4 folders.
    user_id: int
    group_id: int
    home: PurePosixPath


@dataclass(frozen=True)
class UnitFile:
    """One generated unit: its file name and full content."""

    name: str
    content: str
    # Whether `systemctl enable` should link it to boot. A unit without an
    # [Install] section is started by the units that require it instead.
    enable_at_boot: bool


# --- Names -------------------------------------------------------------------


def escape_unit_path(path: PurePosixPath) -> str:
    """Escape a path the way `systemd-escape --path` does.

    A mount unit only loads when its file name is the escaped mount point.
    """
    relative = str(path).strip("/")
    if not relative:
        return UNIT_NAME_PATH_SEPARATOR
    return UNIT_NAME_PATH_SEPARATOR.join(
        _escape_path_component(component) for component in relative.split("/")
    )


def _escape_path_component(component: str) -> str:
    escaped = []
    for position, character in enumerate(component):
        # A leading dot is escaped so the name does not look like a hidden file.
        is_leading_dot = position == 0 and character == "."
        if character in UNESCAPED_UNIT_NAME_CHARACTERS and not is_leading_dot:
            escaped.append(character)
        else:
            escaped.extend(f"\\x{byte:02x}" for byte in character.encode("utf-8"))
    return "".join(escaped)


def mount_unit_name(mount_point: PurePosixPath) -> str:
    return escape_unit_path(mount_point) + MOUNT_UNIT_SUFFIX


def partition_device(partition_uuid: str) -> PurePosixPath:
    return DEVICE_BY_UUID_DIRECTORY / partition_uuid


def library_steamapps(config: InstallConfig) -> PurePosixPath:
    return config.mount_point / config.library_folder / STEAMAPPS_DIRECTORY


def linux_only_data_paths(config: InstallConfig) -> tuple[PurePosixPath, ...]:
    """Return the ext4 folders that are bind-mounted over the library."""
    data_directory = config.home / LINUX_ONLY_DATA_DIRECTORY
    return tuple(data_directory / name for name in LINUX_ONLY_DIRECTORIES)


# --- Units -------------------------------------------------------------------


def build_units(config: InstallConfig) -> list[UnitFile]:
    """Return every unit the setup needs, in dependency order."""
    return [
        render_ntfs3_loader_service(config),
        render_ntfs_mount(config),
        *(render_bind_mount(config, name) for name in LINUX_ONLY_DIRECTORIES),
    ]


def render_ntfs3_loader_service(config: InstallConfig) -> UnitFile:
    ntfs_mount = mount_unit_name(config.mount_point)
    content = f"""\
{GENERATED_HEADER}
[Unit]
Description=Load the ntfs3 kernel module for the shared Steam library
# Some distros (Zorin, for one) blacklist ntfs3 in /etc/modprobe.d.
# /etc/modules-load.d is not used because systemd-modules-load honors that
# blacklist and skips the module. An explicit `modprobe ntfs3` by name does
# not, and it leaves the distro's blacklist untouched.
# The default dependencies would start this after basic.target, which comes
# after local-fs.target, too late for a boot-time mount. Without them it runs
# as early as the mount needs it.
DefaultDependencies=no
Before={ntfs_mount}

[Service]
Type=oneshot
# Stay "active" after modprobe exits, so the mount's Requires= stays satisfied.
RemainAfterExit=yes
ExecStart={MODPROBE_PATH} {NTFS3_KERNEL_MODULE}
"""
    return UnitFile(name=NTFS3_LOADER_SERVICE, content=content, enable_at_boot=False)


def render_ntfs_mount(config: InstallConfig) -> UnitFile:
    device = partition_device(config.partition_uuid)
    options = f"{build_ntfs3_mount_options(config.user_id, config.group_id)},{NOFAIL_OPTION}"
    content = f"""\
{GENERATED_HEADER}
[Unit]
Description=Shared Steam library (NTFS, ntfs3 with windows_names)
# Without the module loaded, mounting fails with "unknown filesystem type":
# the kernel's own module autoload also honors the blacklist.
Requires={NTFS3_LOADER_SERVICE}
After={NTFS3_LOADER_SERVICE}

[Mount]
What={_escape_specifiers(str(device))}
Where={_escape_specifiers(str(config.mount_point))}
Type={NTFS3_FILESYSTEM}
Options={options}

[Install]
WantedBy={LOCAL_FILESYSTEMS_TARGET}
"""
    return UnitFile(name=mount_unit_name(config.mount_point), content=content, enable_at_boot=True)


def render_bind_mount(config: InstallConfig, linux_only_directory: str) -> UnitFile:
    ntfs_mount = mount_unit_name(config.mount_point)
    source = config.home / LINUX_ONLY_DATA_DIRECTORY / linux_only_directory
    target = library_steamapps(config) / linux_only_directory
    content = f"""\
{GENERATED_HEADER}
[Unit]
Description=Keep {linux_only_directory} of the shared Steam library on ext4
# BindsTo= rather than Requires=: if the NTFS partition is unmounted, this
# bind mount is unmounted too, instead of being left over an empty folder
# where Steam would write Linux-only files onto the wrong filesystem.
BindsTo={ntfs_mount}
After={ntfs_mount}

[Mount]
What={_escape_specifiers(str(source))}
Where={_escape_specifiers(str(target))}
Type={BIND_MOUNT_TYPE}
# nofail as on the NTFS mount: without it, this unit would be ordered before
# local-fs.target and, through After= above, make boot wait for a missing disk.
Options={BIND_OPTION},{NOFAIL_OPTION}

[Install]
WantedBy={LOCAL_FILESYSTEMS_TARGET}
"""
    return UnitFile(name=mount_unit_name(target), content=content, enable_at_boot=True)


def _escape_specifiers(value: str) -> str:
    # systemd expands `%` specifiers (such as %h) in these settings, so a
    # literal `%` in a path must be doubled.
    return value.replace("%", "%%")
