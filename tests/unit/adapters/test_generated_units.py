"""Tests for finding the unit files steamshare generated, in a temporary folder."""

import os
from pathlib import Path

from steamshare.adapters.generated_units import find_generated_unit, find_generated_units
from steamshare.core.systemd_units import GENERATED_HEADER

OUR_UNIT = f"{GENERATED_HEADER}\n[Mount]\nWhere=/mnt/steamlib\n"
OLD_HEADER_UNIT = "# Generated by steamshare (`python -m steamshare install`).\n\n[Service]\n"


def test_finds_units_with_either_header_and_skips_the_rest(tmp_path: Path) -> None:
    (tmp_path / "mnt-steamlib.mount").write_text(OUR_UNIT)
    (tmp_path / "steamshare-ntfs3.service").write_text(OLD_HEADER_UNIT)
    # Named like ours, written by the user: never touched.
    (tmp_path / "mnt-steamlib-other.mount").write_text("[Mount]\nWhere=/mnt/other\n")
    (tmp_path / "ssh.service").write_text("[Service]\n")

    units = find_generated_units(tmp_path)

    assert [unit.name for unit in units] == ["mnt-steamlib.mount", "steamshare-ntfs3.service"]
    assert units[0].content == OUR_UNIT


def test_a_units_backups_come_with_it_and_are_not_units_themselves(tmp_path: Path) -> None:
    (tmp_path / "mnt-steamlib.mount").write_text(OUR_UNIT)
    (tmp_path / "mnt-steamlib.mount.bak-20261026-130000").write_text(OUR_UNIT)
    (tmp_path / "mnt-steamlib.mount.bak-20261026-183131").write_text(OUR_UNIT)
    # Another unit whose name starts the same way is not a backup.
    (tmp_path / "mnt-steamlib.mount-not-a-backup").write_text(OUR_UNIT)

    [unit] = find_generated_units(tmp_path)

    assert unit.backups == (
        tmp_path / "mnt-steamlib.mount.bak-20261026-130000",
        tmp_path / "mnt-steamlib.mount.bak-20261026-183131",
    )


def test_links_folders_and_binary_files_are_skipped(tmp_path: Path) -> None:
    target = tmp_path / "elsewhere.mount"
    target.write_text(OUR_UNIT)
    links = tmp_path / "units"
    links.mkdir()
    # systemd's own links, such as enablement links and masks, are not ours.
    os.symlink(target, links / "linked.mount")
    (links / "local-fs.target.wants").mkdir()
    (links / "binary.service").write_bytes(b"\xff\xfe\x00")

    assert find_generated_units(links) == []


def test_a_missing_folder_has_no_units(tmp_path: Path) -> None:
    assert find_generated_units(tmp_path / "missing") == []


def test_finds_one_named_unit_only_when_it_is_ours(tmp_path: Path) -> None:
    ours = tmp_path / "steamshare-watch.service"
    ours.write_text(OUR_UNIT)
    theirs = tmp_path / "theirs.service"
    theirs.write_text("[Service]\n")

    assert find_generated_unit(ours) is not None
    assert find_generated_unit(theirs) is None
    assert find_generated_unit(tmp_path / "missing.service") is None
